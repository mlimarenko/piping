pub const SSH_FILE_UPLOAD_MULTIPART_OVERHEAD_BYTES: usize = 8 * 1024 * 1024;

#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub struct RestRouteLimits {
    pub ssh_file_upload_body_bytes: usize,
}

impl RestRouteLimits {
    pub fn ssh_file_upload_body_bytes(max_upload_bytes: u64) -> usize {
        let max_upload_bytes = usize::try_from(max_upload_bytes).unwrap_or(usize::MAX);
        max_upload_bytes.saturating_add(SSH_FILE_UPLOAD_MULTIPART_OVERHEAD_BYTES)
    }
}

impl Default for RestRouteLimits {
    fn default() -> Self {
        Self {
            ssh_file_upload_body_bytes: Self::ssh_file_upload_body_bytes(
                DEFAULT_PROXY_SSH_FILE_TRANSFER_MAX_UPLOAD_BYTES,
            ),
        }
    }
}

