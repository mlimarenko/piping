#[cfg(test)]
mod tests {
    use axum::{body::Body, body::Bytes, http::Request, http::StatusCode};
    use tower::util::ServiceExt;

    use super::*;

    #[test]
    fn ssh_file_upload_body_limit_includes_multipart_overhead() {
        assert_eq!(
            RestRouteLimits::ssh_file_upload_body_bytes(10),
            10 + SSH_FILE_UPLOAD_MULTIPART_OVERHEAD_BYTES
        );
    }

    #[tokio::test]
    async fn route_body_limit_overrides_outer_global_limit_for_upload_only() {
        let app: Router<()> = Router::new()
            .route(
                "/upload",
                post(|_: Bytes| async { StatusCode::OK }).layer(DefaultBodyLimit::max(16)),
            )
            .route("/other", post(|_: Bytes| async { StatusCode::OK }))
            .layer(DefaultBodyLimit::max(4));

        let upload_response = app
            .clone()
            .oneshot(
                Request::post("/upload")
                    .body(Body::from(vec![0_u8; 8]))
                    .expect("upload request"),
            )
            .await
            .expect("upload response");
        assert_eq!(upload_response.status(), StatusCode::OK);

        let other_response = app
            .oneshot(
                Request::post("/other")
                    .body(Body::from(vec![0_u8; 8]))
                    .expect("other request"),
            )
            .await
            .expect("other response");
        assert_eq!(other_response.status(), StatusCode::PAYLOAD_TOO_LARGE);
    }
}
