/**
 * `schema.gen.ts` freshness guard.
 *
 * The frontend's API types are generated from the API contract by
 * `pnpm gen:api` (`openapi-typescript` over
 * `apps/api/contracts/piping.openapi.yaml`). Nothing else notices when the
 * committed copy drifts: it keeps typechecking against yesterday's routes, so an
 * endpoint that exists in the contract stays invisible to the frontend and a
 * renamed field stays misspelled until runtime. This test runs the very same CLI
 * with the very same arguments as the `gen:api` script writes into a temporary
 * file, then compares that output byte for byte with the committed file — drift
 * fails here. Calling the CLI (rather than the generator's programmatic API)
 * keeps the guard aligned with the command that actually produced the file.
 *
 * The temporary output lives in `os.tmpdir()` and is removed in a `finally`
 * block; nothing is written inside the repository.
 *
 * No DOM is touched, but the file deliberately stays in the suite's default
 * jsdom environment: the shared `src/test/setup.ts` and the `@/shared/i18n`
 * initialisation it imports reach for `window`/`document`, so switching this
 * file to the node environment fails in setup before the test runs. Making the
 * suite node-capable means guarding those shared modules, which is not this
 * check's business.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

// Resolved against the suite's working directory (`apps/web`, where both
// `pnpm run test` and `gen:api` run): under jsdom `import.meta.url` is not a
// `file:` URL, so `fileURLToPath` cannot be used here.
const webRoot = process.cwd();
const cli = join(webRoot, "node_modules", ".bin", "openapi-typescript");
const contract = join(webRoot, "..", "api", "contracts", "piping.openapi.yaml");
const generated = join(webRoot, "src", "shared", "api", "schema.gen.ts");

/** Where two texts first differ, phrased for the assertion message; "" if equal. */
function firstDifference(expected: string, actual: string): string {
  const expectedLines = expected.split("\n");
  const actualLines = actual.split("\n");
  const shared = Math.min(expectedLines.length, actualLines.length);

  for (let index = 0; index < shared; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      return [
        `first difference at line ${index + 1}:`,
        `  contract regenerates -> ${JSON.stringify(expectedLines[index])}`,
        `  committed file has   -> ${JSON.stringify(actualLines[index])}`,
      ].join("\n");
    }
  }
  if (expectedLines.length === actualLines.length) return "";
  return (
    "one file ends earlier: " +
    `the contract regenerates ${expectedLines.length} lines, ` +
    `the committed file has ${actualLines.length}`
  );
}

describe("generated API schema", () => {
  it(
    "schema.gen.ts is the contract regenerated by openapi-typescript",
    { timeout: 120_000 },
    () => {
      const scratch = mkdtempSync(join(tmpdir(), "schema-gen-freshness-"));
      const regenerated = join(scratch, "schema.gen.ts");
      try {
        expect(
          existsSync(cli) && existsSync(contract),
          `missing ${cli} or ${contract}; run the suite from apps/web after pnpm install`,
        ).toBe(true);
        // Mirrors the `gen:api` script in package.json; both sides change
        // together or the guard is meaningless.
        execFileSync(
          cli,
          [contract, "--default-non-nullable", "false", "-o", regenerated],
          { stdio: "pipe" },
        );
        expect(
          firstDifference(readFileSync(regenerated, "utf8"), readFileSync(generated, "utf8")),
          `${generated} does not match ${contract}. ` +
            "Run `pnpm gen:api` in apps/web and commit the regenerated file.",
        ).toBe("");
      } finally {
        rmSync(scratch, { recursive: true, force: true });
      }
    },
  );
});
